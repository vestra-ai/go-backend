// Writes docs/go-server.postman_collection.json from the route metadata every section under src/api/v1 declares:
// one folder per contract section, one request per route. Postman is generated, never hand-edited, so the
// collection, API.md's index and the code cannot drift. Dev-only routes stay out of the app's folders.
// Phase 0 emits the request skeletons (method, path, title, summary); the example bodies, the saved answers and
// the journeys come with phase 6. It writes a file only: nothing is pushed to Postman's cloud.
//   pnpm postman:build
import { writeFileSync } from 'node:fs';
import { sections, type RouteMeta } from '../src/api/v1/index.js';

const OUT = new URL('../docs/go-server.postman_collection.json', import.meta.url);

/** `/app/v1/trips/:trip/messages/:id` → Postman's `{{baseUrl}}/app/v1/trips/:trip/messages/:id` with one variable per `:param`. */
function urlOf(route: RouteMeta) {
  const segments = route.path.split('/').filter(Boolean);
  const variables = segments.filter((s) => s.startsWith(':')).map((s) => ({ key: s.slice(1), value: '', description: `the ${s.slice(1).replace(/_/g, ' ')}` }));
  const query = Object.entries(route.example?.query ?? {}).map(([key, value]) => ({ key, value }));
  const raw = `{{baseUrl}}/${segments.join('/')}${query.length ? `?${query.map((q) => `${q.key}=${q.value}`).join('&')}` : ''}`;
  return { raw, host: ['{{baseUrl}}'], path: segments, ...(variables.length ? { variable: variables } : {}), ...(query.length ? { query } : {}) };
}

function requestOf(route: RouteMeta) {
  const hasBody = route.method !== 'GET' && route.method !== 'DELETE';
  return {
    name: route.title,
    request: {
      method: route.method,
      description: route.summary,
      header: [
        ...(hasBody ? [{ key: 'Content-Type', value: 'application/json' }] : []),
        ...(hasBody ? [{ key: 'Idempotency-Key', value: '{{$guid}}', description: 'One key per press; send the same one when you retry.' }] : []),
      ],
      ...(route.auth === 'none' ? { auth: { type: 'noauth' } } : {}),
      url: urlOf(route),
      ...(hasBody ? { body: { mode: 'raw', raw: JSON.stringify(route.example?.body ?? {}, null, 2), options: { raw: { language: 'json' } } } } : {}),
    },
    response: (route.example?.responses ?? []).map((r) => ({
      name: r.name,
      code: r.status,
      status: String(r.status),
      header: [{ key: 'Content-Type', value: 'application/json' }],
      body: r.body === undefined ? '' : JSON.stringify(r.body, null, 2),
      originalRequest: { method: route.method, url: urlOf(route) },
    })),
  };
}

export function buildCollection() {
  const folders = new Map<string, ReturnType<typeof requestOf>[]>();
  for (const section of sections) {
    for (const route of section.routes) {
      if (route.dev) continue; // local only: documented in the README, not here
      if (!folders.has(route.section)) folders.set(route.section, []);
      folders.get(route.section)!.push(requestOf(route));
    }
  }
  return {
    info: {
      name: 'Go Server: App API (v1)',
      description: [
        'Everything the app calls on the Go Server, under `/app/v1`, in the app contract\'s section order. Generated by `pnpm postman:build` from the routes\' own metadata (src/api/v1): do not edit by hand.',
        '',
        'Sign in with a Supabase access token: `Authorization: Bearer {{token}}` (the collection\'s auth). Locally, `pnpm dev:stack` runs a fake Supabase Auth: `GET {{authUrl}}/mint?name=Priya&email=priya@gmail.com` gives a token.',
        '',
        'Every write may carry an `Idempotency-Key` (one per press; the same one on a retry replays the first answer). Errors always look like `{"error": {"code", "message", "field", "retry_after_seconds", "request_id"}}`. Money is whole paise. Full reference: docs/API.md.',
      ].join('\n'),
      schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
    },
    auth: { type: 'bearer', bearer: [{ key: 'token', value: '{{token}}', type: 'string' }] },
    variable: [
      { key: 'baseUrl', value: 'http://localhost:8080' },
      { key: 'authUrl', value: 'http://127.0.0.1:54331' },
      { key: 'simUrl', value: 'http://localhost:8090' },
      { key: 'token', value: '' },
      { key: 'tripId', value: '' },
    ],
    item: [...folders].map(([name, item]) => ({ name, item })),
  };
}

if (process.argv[1] && import.meta.url === new URL(process.argv[1], 'file:').href) {
  const collection = buildCollection();
  writeFileSync(OUT, `${JSON.stringify(collection, null, 2)}\n`);
  const n = collection.item.reduce((sum, f) => sum + f.item.length, 0);
  console.log(`wrote ${OUT.pathname}: ${collection.item.length} folders, ${n} requests`);
}
